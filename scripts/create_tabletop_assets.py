"""Author original demo OBJ assets and a scene; no external Python packages needed.

Run from any directory: python scripts/create_tabletop_assets.py
Existing asset filenames are regenerated deterministically.
"""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


class Mesh:
    def __init__(self):
        self.vertices, self.faces = [], []

    def v(self, point):
        self.vertices.append(point)
        return len(self.vertices)

    def tri(self, a, b, c):
        p, q, r = (self.vertices[i - 1] for i in (a, b, c))
        u, v = [q[i] - p[i] for i in range(3)], [r[i] - p[i] for i in range(3)]
        normal = (u[1]*v[2]-u[2]*v[1], u[2]*v[0]-u[0]*v[2], u[0]*v[1]-u[1]*v[0])
        if sum(x*x for x in normal) > 1e-14:
            self.faces.append((a, b, c))

    def quad(self, a, b, c, d):
        self.tri(a, b, c)
        self.tri(a, c, d)

    def box(self, low, high):
        a = [self.v((high[0] if i & 1 else low[0], high[1] if i & 2 else low[1],
                     high[2] if i & 4 else low[2])) for i in range(8)]
        for indices in ((0,2,3,1), (4,5,7,6), (0,1,5,4), (2,6,7,3), (0,4,6,2), (1,3,7,5)):
            self.quad(*(a[i] for i in indices))

    def save(self, filename):
        folder = ROOT / "assets/models/tabletop"
        folder.mkdir(parents=True, exist_ok=True)
        low = [min(p[i] for p in self.vertices) for i in range(3)]
        high = [max(p[i] for p in self.vertices) for i in range(3)]
        span = max(high[i] - low[i] for i in range(3))
        lines = ["# Original CO3059 demo asset; generated by scripts/create_tabletop_assets.py"]
        lines += ["v " + " ".join(f"{x:.8f}" for x in p) for p in self.vertices]
        # UVs are provided per vertex; geometry normals are generated by the existing importer.
        lines += [f"vt {(p[0]-low[0])/span:.8f} {(p[2]-low[2])/span:.8f}" for p in self.vertices]
        lines += ["f " + " ".join(f"{i}/{i}" for i in face) for face in self.faces]
        (folder / filename).write_text("\n".join(lines) + "\n", encoding="utf-8")
        return [(low[i] - (low[i]+high[i])/2) * 2/span for i in range(3)], span


def build():
    table = Mesh()
    table.box((-3,-0.14,-2), (3,0,2))
    for x in (-2.65,2.65):
        for z in (-1.65,1.65):
            table.box((x-0.12,-2.1,z-0.12), (x+0.12,-0.14,z+0.12))
    table.save("table.obj")
    book = Mesh()
    book.box((-1,-0.15,-0.7), (1,0.15,0.7))
    book.save("book.obj")
    ball = Mesh()
    rings = []
    for j in range(17):
        phi = math.pi*j/16
        rings.append([ball.v((math.sin(phi)*math.cos(2*math.pi*i/32), math.cos(phi),
                              math.sin(phi)*math.sin(2*math.pi*i/32))) for i in range(32)])
    for j in range(16):
        for i in range(32):
            k = (i+1) % 32
            ball.quad(rings[j][i], rings[j+1][i], rings[j+1][k], rings[j][k])
    ball.save("ball.obj")
    cup = Mesh()
    rings = [[cup.v((r*math.cos(2*math.pi*i/40), y, r*math.sin(2*math.pi*i/40)))
              for i in range(40)] for r,y in ((0.62,0), (0.62,1.5), (0.50,1.5), (0.50,0.12))]
    for j,k in ((0,1),(1,2),(2,3)):
        for i in range(40):
            n = (i+1) % 40
            cup.quad(rings[j][i], rings[k][i], rings[k][n], rings[j][n])
    outside, inside = cup.v((0,0,0)), cup.v((0,0.12,0))
    for i in range(40):
        n = (i+1) % 40
        cup.tri(outside, rings[0][n], rings[0][i])
        cup.tri(inside, rings[3][i], rings[3][n])
    handle = []
    for i in range(32):
        a = 2*math.pi*i/32
        handle.append([cup.v((0.65+(0.42+0.10*math.cos(b))*math.cos(a),
                              0.75+(0.42+0.10*math.cos(b))*math.sin(a), 0.10*math.sin(b)))
                       for b in (2*math.pi*j/10 for j in range(10))])
    for i in range(32):
        for j in range(10):
            cup.quad(handle[i][j], handle[(i+1)%32][j], handle[(i+1)%32][(j+1)%10], handle[i][(j+1)%10])
    cup_low, _ = cup.save("cup.obj")

    def obj(name, model, category, scale, position, color, yaw=0, randomize=True):
        return {"name": name, "kind": 2, "category_id": category,
                "category_name": ("table","cup","book","ball")[category-1],
                "visible": True, "randomize_transform": randomize,
                "model": "../models/tabletop/" + model, "position": position,
                "rotation": [0,yaw,0], "scale": scale,
                "material": {"color": color, "mode": 2, "shininess": 32, "texture": ""}}

    scene = {"format": "CGAssignment1", "version": 1, "selectedIndex": -1, "showGrid": False,
             "camera": {"target": [0,-0.25,0], "yaw": 25, "pitch": 28, "distance": 8.5,
                        "moveSpeed": 5, "frontView": False},
             "animation": {"playing": False, "speed": 1, "time": 0},
             "background": [0.16,0.19,0.23], "lightPosition": [3,6,4],
             "objects": [obj("Table", "table.obj", 1, [3,3,3], [0,-1.05,0], [0.45,0.28,0.12], randomize=False),
                         obj("Cup A", "cup.obj", 2, [0.65]*3, [-0.95,-cup_low[1]*0.65+0.005,0.15], [0.8,0.16,0.12], 15),
                         obj("Cup B", "cup.obj", 2, [0.55]*3, [0.10,-cup_low[1]*0.55+0.005,-0.7], [0.12,0.60,0.7], -30),
                         obj("Book", "book.obj", 3, [0.70]*3, [1.10,0.11,0.3], [0.12,0.20,0.75], -20),
                         obj("Ball", "ball.obj", 4, [0.42]*3, [-0.20,0.425,1.1], [0.95,0.55,0.08])]}
    folder = ROOT / "assets/scenes"
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "tabletop.json").write_text(json.dumps(scene, indent=2) + "\n", encoding="utf-8")
    config = ROOT / "assets/configs"
    config.mkdir(parents=True, exist_ok=True)
    (config / "batch_demo.json").write_text(json.dumps({"count": 8, "seed": 42, "width": 640, "height": 480,
        "transforms": True, "materials": True, "textures": True, "camera": True, "lighting": True,
        "background": True, "position_jitter": 0.2, "yaw_jitter_degrees": 20,
        "scale_jitter_fraction": 0.1, "camera_yaw_jitter_degrees": 12,
        "camera_pitch_jitter_degrees": 5, "camera_distance_jitter_fraction": 0.08,
        "texture_pool": ["../textures/checker.png", "../textures/checker.jpg"]}, indent=2) + "\n", encoding="utf-8")
    print("Created original table/cup/book/ball OBJ assets, tabletop scene and batch config.")


if __name__ == "__main__":
    build()
